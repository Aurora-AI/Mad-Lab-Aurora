import json
import os
from typing import Dict
from bff_contracts import BFFAdapterSpec, APIManifestEntry

def load_api_manifest(manifest_path: str = None) -> Dict[str, APIManifestEntry]:
    """Carrega e valida o manifesto estático da API."""
    if manifest_path is None:
        manifest_path = os.path.join(os.path.dirname(__file__), "api_manifest.json")
    with open(manifest_path, 'r') as f:
        raw_data = json.load(f)
    return {k: APIManifestEntry(**v) for k, v in raw_data.items()}

def generate_types_file(spec: BFFAdapterSpec) -> str:
    """Gera o SynthesizedPage.types.ts com as interfaces exatas."""
    imports = set()
    props_decl = []

    for dep in spec.props_contract.dependencies:
        imports.add(f"import type {{ {dep.schema_ref} }} from '@/schemas';")
        prop_type = dep.schema_ref
        optional_flag = "" if dep.required else "?"
        props_decl.append(f"  {dep.prop_name}{optional_flag}: {prop_type};")

    code = "/**\n * AUTO-GENERATED BY AURORA BFF COUPLER\n * DO NOT EDIT MANUALLY\n */\n\n"
    code += "\n".join(sorted(imports)) + "\n\n"
    code += "export interface SynthesizedPageProps {\n"
    code += "\n".join(props_decl) + "\n"
    code += "}\n"
    
    return code

def generate_client_component(spec: BFFAdapterSpec, jsx_body: str, imports: set) -> str:
    """
    Invólucro para o SynthesizedPage.client.tsx gerado pela OS-005.
    Aqui injetamos as props, os imports e o corpo do JSX.
    """
    code = "/**\n * AUTO-GENERATED BY AURORA FRONTEND FACTORY\n * PRAGMA: USE CLIENT\n */\n"
    code += "'use client';\n\n"
    code += "import type { SynthesizedPageProps } from './SynthesizedPage.types';\n"
    if imports:
        valid_imports = [imp for imp in imports if imp]
        if valid_imports:
            code += "\n".join(sorted(valid_imports)) + "\n"
    code += "\n"
    code += "export default function SynthesizedPageClient(props: SynthesizedPageProps) {\n"
    code += "  return (\n"
    code += f"{jsx_body}\n"
    code += "  );\n"
    code += "}\n"
    
    return code

def generate_server_component(spec: BFFAdapterSpec, manifest: Dict[str, APIManifestEntry]) -> str:
    """Gera o page.tsx atuando como BFF com regras estritas de error_strategy e cache."""
    code = "/**\n * AUTO-GENERATED SERVER COMPONENT (BFF)\n * TRUSTWARE CERTIFIED DATA COUPLER\n */\n\n"
    code += "import SynthesizedPageClient from './SynthesizedPage.client';\n"
    
    fetch_blocks = []
    prop_assignments = []
    
    for dep in spec.props_contract.dependencies:
        if dep.adapter_ref not in manifest:
            raise ValueError(f"FALHA DE LIGAÇÃO: Adapter '{dep.adapter_ref}' não existe no manifesto da API.")
        
        endpoint = manifest[dep.adapter_ref]
        
        # Mapeamento estrito da estratégia de erro
        error_handling = ""
        if dep.error_strategy == "boundary":
            error_handling = "throw new Error(`BFF Fetch Error: ${res.statusText}`);"
        elif dep.error_strategy == "null":
            error_handling = f"{dep.prop_name} = null;"
        elif dep.error_strategy == "fallback":
            error_handling = f"{dep.prop_name} = {{}}; // Configurado para fallback vazio"

        # Bloco Try/Catch
        fetch_block = f"""  let {dep.prop_name} = null;
  try {{
    const res = await fetch(process.env.INTERNAL_API_GATEWAY + '{endpoint.path}', {{
      method: '{endpoint.method}',
      cache: '{dep.cache_policy}',
      headers: {{
        'Authorization': `Bearer ${{process.env.BFF_INTERNAL_TOKEN}}`,
        'X-Aurora-Scope': '{dep.access_scope}'
      }}
    }});
    if (!res.ok) {{
      {error_handling}
    }} else {{
      {dep.prop_name} = await res.json();
    }}
  }} catch (error) {{
    {error_handling.replace('res.statusText', 'error.message')}
  }}"""
        fetch_blocks.append(fetch_block)
        prop_assignments.append(f"{dep.prop_name}={{{dep.prop_name}}}")

    code += "\nexport default async function Page() {\n"
    code += "\n".join(fetch_blocks) + "\n\n"
    code += f"  return <SynthesizedPageClient {(' '.join(prop_assignments))} />;\n"
    code += "}\n"
    
    return code

